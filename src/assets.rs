mod tests {
    use super::*;

    #[test]
    fn supplies_every_mdx_preview_icon() {
        for path in [
            "icons/book-open.svg",
            "icons/file.svg",
            "icons/folder.svg",
            "icons/globe.svg",
            "icons/heart.svg",
            "icons/info.svg",
            "icons/map.svg",
            "icons/star.svg",
            "icons/square-terminal.svg",
            "icons/user.svg",
        ] {
            assert!(Assets.load(path).unwrap().is_some(), "missing {path}");
        }
    }
}
